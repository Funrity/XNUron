#!/bin/sh
# Rebuilds the test guest kernel and regenerates app/src/main/cpp/guest_image.h
# (needs clang, ld.lld, llvm-objcopy).  The generated header is committed so the
# Android build does not need these tools.
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd); T=$(mktemp -d)
CC=${CC:-clang}; LLD=${LLD:-ld.lld}; OBJCOPY=${OBJCOPY:-llvm-objcopy}
FLAGS="--target=aarch64-none-elf -O2 -ffreestanding -fno-builtin -mgeneral-regs-only -mstrict-align -fno-stack-protector -fno-pic -w"
$CC $FLAGS -c "$ROOT/guest/start.S" -o "$T/start.o"
$CC $FLAGS -c "$ROOT/guest/kernel.c" -o "$T/kernel.o"
$LLD -static -nostdlib -T "$ROOT/guest/link.ld" "$T/start.o" "$T/kernel.o" -o "$T/guest.elf"
$OBJCOPY -O binary "$T/guest.elf" "$T/guest.bin"
cp "$T/guest.bin" "${GUEST_BIN_OUT:-$ROOT/guest/guest.bin}"
python3 - "$T/guest.bin" "$ROOT/app/src/main/cpp/guest_image.h" <<'PY'
import sys
d = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as f:
    f.write("/* GENERATED by tools/build_guest.sh from the sources in guest/ - do not edit. */\n")
    f.write("#pragma once\n#include <stddef.h>\n#include <stdint.h>\n")
    f.write("static const uint8_t a64_guest_image[%d] = {\n" % len(d))
    for i in range(0, len(d), 16):
        f.write("  " + ",".join("0x%02x" % b for b in d[i:i+16]) + ",\n")
    f.write("};\nstatic const size_t a64_guest_image_size = %d;\n" % len(d))
PY
echo "guest: $(wc -c < "$T/guest.bin") bytes"
